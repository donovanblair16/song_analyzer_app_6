    def validate_inputs(self):
        """Validate inputs before closing dialog"""
        # Check at least one feature is selected
        selected_features = [f for f in ALL_FEATURE_KEYS if self.feature_vars[f].get()]
        if not selected_features:
            messagebox.showerror("Selection Error", "You must select at least one feature.")
            return False
        
        # Validate feature weights
        try:
            weights = {}
            for feature in selected_features:
                weight = float(self.weight_vars[feature].get())
                if weight <= 0:
                    messagebox.showerror("Input Error", f"Weight for {feature} must be positive.")
                    return False
                weights[feature] = weight
        except ValueError:
            messagebox.showerror("Input Error", "All weights must be valid numbers.")
            return False
        
        # Validate mixture count
        try:
            n_mixtures = int(self.mixture_var.get())
            if n_mixtures < 1 or n_mixtures > 10:
                messagebox.showerror("Input Error", "Number of mixtures must be between 1 and 10.")
                return False
        except ValueError:
            messagebox.showerror("Input Error", "Number of mixtures must be a valid integer.")
            return False
            
        # Validate min_covar
        try:
            min_covar = float(self.min_covar_var.get())
            if min_covar <= 0:
                messagebox.showerror("Input Error", "Minimum covariance must be positive.")
                return False
        except ValueError:
            messagebox.showerror("Input Error", "Minimum covariance must be a valid number.")
            return False
            
        # Validate data cleaning parameters
        if self.enable_outlier_removal.get():
            try:
                z_threshold = float(self.outlier_z_threshold.get())
                if z_threshold <= 0:
                    messagebox.showerror("Input Error", "Z-score threshold must be positive.")
                    return False
            except ValueError:
                messagebox.showerror("Input Error", "Z-score threshold must be a valid number.")
                return False
                
        if self.enable_short_section_removal.get():
            try:
                min_bars = float(self.short_section_min_bars.get())
                if min_bars <= 0:
                    messagebox.showerror("Input Error", "Minimum bars must be positive.")
                    return False
            except ValueError:
                messagebox.showerror("Input Error", "Minimum bars must be a valid number.")
                return False
        
        # Store values
        self.selected_features = selected_features
        self.feature_weights = weights
        self.n_mixtures = n_mixtures
        self.min_covar = min_covar
        return True
    
