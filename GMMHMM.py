def export_analysis_results(model_info, data_cleaning_info, feature_keys, feature_weights, model_path, raw_averages=None):
    """
    Export the model analysis results and data cleaning information to a JSON file.
    
    Args:
        model_info (dict): Dictionary containing model analysis information
        data_cleaning_info (dict): Dictionary containing data cleaning information
        feature_keys (list): List of feature names used in the model
        feature_weights (dict): Dictionary of feature weights
        model_path (str): Path to the saved model (used to generate output filename)
        raw_averages (dict, optional): Dictionary containing raw feature averages by label
    
    Returns:
        str: Path to the exported file
    """
    # Create export data structure
    export_data = {
        "timestamp": datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        "model_name": os.path.basename(model_path),
        "feature_keys": feature_keys,
        "feature_weights": {k: float(v) for k, v in feature_weights.items()},
        "model_analysis": model_info,
        "data_cleaning": data_cleaning_info,
        "cleaning_settings": {
            "outlier_removal": {
                "enabled": ENABLE_OUTLIER_REMOVAL,
                "z_threshold": float(OUTLIER_Z_THRESHOLD) if ENABLE_OUTLIER_REMOVAL else None
            },
            "short_section_removal": {
                "enabled": ENABLE_SHORT_SECTION_REMOVAL,
                "min_bars": float(SHORT_SECTION_MIN_BARS) if ENABLE_SHORT_SECTION_REMOVAL else None
            },
            "consistency_filtering": {
                "enabled": ENABLE_CONSISTENCY_FILTERING
            }
        }
    }
    
    # Add raw averages if provided
    if raw_averages is not None:
        # Add debug statements to check if avg_rms is present
        for label in raw_averages:
            if 'avg_rms' in raw_averages[label]:
                print(f"EXPORT DEBUG: Raw Average RMS for {label}: {raw_averages[label]['avg_rms']:.4f}")
            else:
                print(f"EXPORT DEBUG: No avg_rms in raw_averages for {label}!")
    
        export_data["raw_feature_averages"] = raw_averages
    
    # Generate output filename based on model path
    base_name = os.path.splitext(os.path.basename(model_path))[0]
    output_path = os.path.join(os.path.dirname(model_path), f"{base_name}_analysis.json")
    
    # Save to file
    try:
    # Define a custom encoder function to handle NumPy types
        def np_encoder(obj):
            if isinstance(obj, np.integer):
                return int(obj)
            elif isinstance(obj, np.floating):
                return float(obj)
            elif isinstance(obj, np.ndarray):
                return obj.tolist()
            return obj

        with open(output_path, 'w') as f:
            json.dump(export_data, f, indent=2, default=np_encoder)
        print(f"\nAnalysis results exported to: {output_path}")
        return output_path
    except Exception as e:
        print(f"\nERROR: Failed to export analysis results: {e}")
        traceback.print_exc()
        return None

